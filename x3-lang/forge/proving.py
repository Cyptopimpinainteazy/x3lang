"""Proving Ground: attack the compiled build with the repository's own checkers.

Payment probes are real agent intents (`intent … under mandate …`), compiled by
`near_intents.compile_program`, turned into a dry 1Click request, and judged by
`near_intents.check_against_mandate` — the `near_intents.py mandate check` path, which runs
x3-guard's `check_mandate` checks in the contract's order. Probes that need chain state the
compiled file cannot hold (an expired clock, prior spending, a revoked mandate) call the same
`check_mandate` with that state supplied, and say so.

Delegation probes call `agent_constitution.check_admission` with the built agent as parent.
Nothing here sends a transaction or contacts a network.
"""
from __future__ import annotations

import hashlib
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

import near_intents as ni
import registry as chain_registry
from agent_constitution import AgentManifest, check_admission

from .core import Assets, manifest_from_dict

ENGINE_CHECK = "near_intents.check_against_mandate (x3-guard check_mandate order)"
ENGINE_STATE = "near_mandate.check_mandate with supplied chain state"
ENGINE_ADMISSION = "agent_constitution.check_admission"

# A valid-looking address on each chain that no build may list, used as the attacker.
_ATTACKERS = {
    "near": "forge-attacker.near",
    "solana": "AttackerAttackerAttackerAttackerAttacker1",
    "ethereum": "0x000000000000000000000000000000000000dEaD",
    "bsc": "0x000000000000000000000000000000000000dEaD",
}


def _other_address(chain: str, avoid: List[str], salt: str) -> str:
    base = _ATTACKERS.get(chain)
    if base and base not in avoid and chain_registry.is_valid_receiver(chain, base):
        return base
    if chain == "near":
        return f"forge-{salt}.near"
    raise ValueError(f"no probe address for {chain}")


def _intent_source(name: str, *, spend: str, amount: str, refund_from: str, dest: str, recipient: str, owner: str,
                   slippage: str, fees: int) -> str:
    return "\n".join([
        f"// Proving Ground probe `{name}`, generated by X3 Agent Forge.",
        f"intent forge_probe_{name} {{",
        f"    from {spend} amount {amount} receiver {refund_from}",
        f"    to {dest} receiver {recipient}",
        "    route {",
        f"        bridge NearIntents {spend} -> {dest} min_receive 1;",
        "    }",
        f"    under mandate {owner}",
        f"    require slippage <= {slippage}%",
        f"    require fees <= {fees} bps",
        f"    require nonce unused forge_{name}",
        f"    timeout 10m refund {spend}",
        "    on_fail rollback",
        "}",
        "",
    ])


def _run_intent(workdir: Path, source: str, name: str, mandate_path: Path, assets: Assets, now: datetime):
    path = workdir / f"probe_{name}.x3"
    path.write_text(source)
    _, leg = ni.compile_program(str(path), now=now)
    request = ni.build_quote_request(leg, assets.tokens, dry=True)
    sha = hashlib.sha256(path.read_bytes()).hexdigest()
    return leg, request, sha


def _matches(entry: Dict[str, Any], expect: str, guard: Optional[str]) -> bool:
    if entry["outcome"] != expect:
        return False
    if guard is None:
        return True
    return guard in [c["guard"] for c in entry["checks"] if not c["ok"]]


def _verdict(checks: List[Dict[str, Any]]) -> str:
    return "allow" if all(c["ok"] for c in checks) else "deny"


def _payment_probes(result: Dict[str, Any], assets: Assets, workdir: Path, now: datetime) -> List[Dict[str, Any]]:
    norm = result["normalized"]
    sp, pay = norm["skills"]["spend"], norm["skills"]["payees"]
    owner = norm["identity"]["owner"]
    spend_ref, dest_ref = sp["asset"], pay["assets"][0]
    spend_chain = assets.by_ref[spend_ref]["chain"]
    dest_chain = assets.by_ref[dest_ref]["chain"]
    per_payment = int(sp["per_payment"]["base_units"])
    daily = int(sp["per_24h"]["base_units"])
    cos = norm["skills"].get("cosign")
    approve_above = int(cos["above"]["base_units"]) if cos else None
    ok_amount = max(1, min(per_payment, approve_above or per_payment) // 2)
    recipient = next((r for r in pay["recipients"] if chain_registry.is_valid_receiver(dest_chain, r)), None)
    slippage = sp["max_slippage"]
    fees = sp["max_fees"]
    refund = sp["refund_to"]

    mandate_path = workdir / "agent.x3"
    mandate_path.write_text(result["source"])
    m = ni.mandates()
    compiled = result["compiled"]
    base_mandate = {"owner": compiled["owner"], "agent": compiled["agent"], "terms": compiled["terms"],
                    "version": None, "revoked": False, "spends": []}
    now_ms = int(now.timestamp() * 1000)
    probes: List[Dict[str, Any]] = []

    def intent(name: str, **over: Any) -> str:
        fields = dict(spend=spend_ref, amount=str(ok_amount), refund_from=refund, dest=dest_ref,
                      recipient=recipient, owner=owner, slippage=slippage, fees=fees)
        fields.update(over)
        return _intent_source(name, **fields)

    def via_check(pid: str, title: str, expect: str, source: str, *, note: str = "",
                  guard: Optional[str] = None) -> Dict[str, Any]:
        entry: Dict[str, Any] = {"id": pid, "title": title, "expect": expect, "engine": ENGINE_CHECK,
                                 "intent_source": source, "note": note, "expect_guard": guard}
        try:
            leg, request, sha = _run_intent(workdir, source, pid, mandate_path, assets, now)
        except ni.NearIntentsError as exc:
            # The intent compiler itself refused it before any mandate check.
            entry.update(outcome="deny", checks=[{"guard": exc.code, "ok": False, "detail": exc.message}],
                         stage="intent compiler")
            entry["ok"] = entry["outcome"] == expect
            return entry
        try:
            out = ni.check_against_mandate(leg, request, sha, str(mandate_path), tokens=assets.tokens, now=now)
            entry.update(outcome="allow", checks=out["checks"], approvals_needed=out["approvals_needed"])
        except ni.NearIntentsError as exc:
            if exc.code != "X3_MANDATE_DENIED" or not isinstance(exc.detail, dict):
                entry.update(outcome="deny", checks=[{"guard": exc.code, "ok": False, "detail": exc.message}],
                             stage="mandate binding")
            else:
                entry.update(outcome="deny", checks=exc.detail["checks"],
                             approvals_needed=exc.detail.get("approvals_needed", 0))
        entry["stage"] = entry.get("stage", "mandate check")
        if expect == "approval":
            entry["ok"] = entry["outcome"] == "allow" and entry.get("approvals_needed", 0) > 0
        else:
            entry["ok"] = _matches(entry, expect, guard)
        return entry

    def via_state(pid: str, title: str, expect: str, mandate: Dict[str, Any], at_ms: int, note: str,
                  guard: str) -> Dict[str, Any]:
        source = intent(pid)
        leg, request, sha = _run_intent(workdir, source, pid, mandate_path, assets, now)
        policy = ni.policy_for(leg, request, sha)
        checks = m.check_mandate(mandate, policy, at_ms)
        outcome = _verdict(checks)
        entry = {"id": pid, "title": title, "expect": expect, "engine": ENGINE_STATE, "intent_source": source,
                 "note": note, "outcome": outcome, "checks": checks, "stage": "mandate check", "expect_guard": guard}
        entry["ok"] = _matches(entry, expect, guard)
        return entry

    if recipient is None:
        probes.append({"id": "permitted", "title": "Permitted payment", "expect": "allow", "outcome": "deny",
                       "ok": False, "engine": ENGINE_CHECK, "stage": "probe setup", "intent_source": "",
                       "checks": [{"guard": "probe", "ok": False,
                                   "detail": f"no allowed recipient is an address on {dest_chain}"}], "note": ""})
        return probes

    probes.append(via_check("permitted", f"Pay {ok_amount} base units to {recipient}", "allow", intent("permitted")))
    attacker = _other_address(dest_chain, pay["recipients"], "recipient")
    probes.append(via_check("forbidden_recipient", f"Pay an unlisted recipient ({attacker})", "deny",
                            intent("forbidden_recipient", recipient=attacker), guard="mandate_recipient"))
    probes.append(via_check("over_cap", f"Pay {per_payment + 1} base units, one over the per-payment cap", "deny",
                            intent("over_cap", amount=str(per_payment + 1)), guard="mandate_per_payment"))
    hijack = _other_address(spend_chain, [refund], "refund")
    probes.append(via_check("refund_hijack", f"Point refunds at {hijack}", "deny",
                            intent("refund_hijack", refund_from=hijack), guard="mandate_refund_to"))
    if cos and approve_above is not None and approve_above + 1 <= per_payment:
        probes.append(via_check("needs_approval", f"Pay {approve_above + 1} base units, above the co-sign line",
                                "approval", intent("needs_approval", amount=str(approve_above + 1)),
                                note="Allowed only after the listed approvers sign approve_intent."))
    expires_ms = int(compiled["terms"]["expires_at_ms"])
    probes.append(via_state("expired", "Pay after the mandate expires", "deny", base_mandate, expires_ms + 1,
                            "Clock set 1 ms past expires_at_ms.", "mandate_active"))
    prior = max(daily - ok_amount + 1, 1)
    spent = dict(base_mandate, spends=[{"amount": str(prior), "at_ms": now_ms - 3_600_000}])
    probes.append(via_state("over_daily", "Pay after the rolling 24h budget is used up", "deny", spent, now_ms,
                            f"Supplied state: {prior} base units already spent an hour ago. On chain, x3-guard "
                            "records real spends.", "mandate_daily"))
    revoked = dict(base_mandate, revoked=True, version=2)
    probes.append(via_state("revoked", "Pay after the owner revokes the mandate", "deny", revoked, now_ms,
                            "Supplied state: revoke_mandate has been sent.", "mandate_active"))
    return probes


def _admission_probes(result: Dict[str, Any], now_s: int) -> List[Dict[str, Any]]:
    parent = manifest_from_dict(result["manifest"])
    one_cap = sorted(parent.capabilities)[:1]
    one_surface = sorted(parent.surfaces)[:1]
    child_expiry = min(parent.expires_at, now_s + 86_400)

    def child(cid: str, caps: List[str], surfaces: List[str]) -> AgentManifest:
        return AgentManifest(agent_id=f"{cid}.{parent.agent_id}"[:64], parent_id=parent.agent_id,
                             capabilities=frozenset(caps), surfaces=frozenset(surfaces),
                             budget=max(1, parent.budget // 4), expires_at=child_expiry, lineage=(parent.agent_id,),
                             spawn_limit=0)

    def run(pid: str, title: str, expect: str, candidate: AgentManifest, approved: bool, note: str,
            reason: Optional[str] = None) -> Dict[str, Any]:
        d = check_admission(candidate, parent, now=now_s, existing_ids=frozenset({parent.agent_id}),
                            parent_budget_available=parent.budget, parent_children=0, approval_verified=approved)
        outcome = "allow" if d.allowed else "deny"
        ok = outcome == expect and (reason is None or reason in d.reasons)
        return {"id": pid, "expect_guard": reason, "title": title, "expect": expect, "engine": ENGINE_ADMISSION, "note": note,
                "outcome": outcome, "ok": ok, "stage": "admission",
                "checks": [{"guard": r, "ok": False, "detail": "refused"} for r in d.reasons] or
                          [{"guard": "admission", "ok": True, "detail": "every admission check passed"}],
                "candidate": {"capabilities": sorted(candidate.capabilities), "surfaces": sorted(candidate.surfaces)}}

    can_spawn = parent.spawn_limit > 0
    probes = [
        run("child_within", "Spawn a child with a subset of its rights", "allow" if can_spawn else "deny",
            child("child", one_cap, one_surface), True,
            "Allowed only with Brood Mother (spawn limit > 0)." if can_spawn else
            "No Brood Mother skill: spawn limit is 0, so even a smaller child is refused.",
            None if can_spawn else "spawn_limit"),
        run("child_escalate_capability", "Hand a child a capability it doesn't hold", "deny",
            child("esc", sorted(parent.capabilities | {"deploy.release", "forge.escalate"}), one_surface), True,
            "No privilege escalation through delegation.", "capabilities"),
        run("child_escalate_surface", "Hand a child a connection it doesn't hold", "deny",
            child("esc2", one_cap, sorted(parent.surfaces | {"pay.unlisted"})), True,
            "A child can't reach a surface its parent can't.", "surfaces"),
        run("child_unapproved", "Spawn a child without owner approval", "deny",
            child("rogue", one_cap, one_surface), False, "Approval must come from a trusted signature check.",
            "approval"),
    ]
    return probes


def prove(result: Dict[str, Any], assets: Assets, workdir: Path, *, now: Optional[datetime] = None) -> Dict[str, Any]:
    now = now or datetime.now(timezone.utc)
    probes: List[Dict[str, Any]] = []
    if result["compiled"] is not None:
        probes.extend(_payment_probes(result, assets, workdir, now))
    else:
        probes.append({"id": "no_spend", "title": "Try to pay with no spending skill", "expect": "deny",
                       "outcome": "deny", "ok": True, "engine": "structural", "stage": "mandate",
                       "intent_source": "", "note": "No Armory Access skill, so no mandate is generated. x3-guard "
                       "holds no mandate for this agent and refuses every agent payment method.",
                       "checks": [{"guard": "mandate_exists", "ok": False, "detail": "no mandate compiled"}]})
    probes.extend(_admission_probes(result, int(now.timestamp())))
    return {"build_hash": result["build_hash"], "ran_at": now.isoformat().replace("+00:00", "Z"),
            "passed": all(p["ok"] for p in probes), "probes": probes}
