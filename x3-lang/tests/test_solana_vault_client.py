def write_keypair(tmp_path, name, seed, *, mode=0o600, public=None):
    path = tmp_path / name
    path.write_text(json.dumps(list(seed + (public or vc.ed25519.public_key(seed)))))
    os.chmod(path, mode)
    return str(path)


def test_keypair_loads_and_never_reveals_the_secret(tmp_path):
    keypair = vc.load_keypair(write_keypair(tmp_path, "owner.json", OWNER_SEED))
    assert keypair.public == OWNER
    assert OWNER_SEED.hex() not in repr(keypair) and str(list(OWNER_SEED)) not in repr(keypair)


def test_keypair_refuses_loose_permissions_symlinks_and_inconsistent_files(tmp_path):
    with pytest.raises(vc.VaultClientError, match="chmod 600"):
        vc.load_keypair(write_keypair(tmp_path, "loose.json", OWNER_SEED, mode=0o644))
    real = write_keypair(tmp_path, "real.json", OWNER_SEED)
    link = tmp_path / "link.json"
    link.symlink_to(real)
    with pytest.raises(vc.VaultClientError, match="regular file"):
        vc.load_keypair(str(link))
    with pytest.raises(vc.VaultClientError, match="inconsistent"):
        vc.load_keypair(write_keypair(tmp_path, "mixed.json", OWNER_SEED, public=AGENT))
    short = tmp_path / "short.json"
    short.write_text("[1, 2, 3]")
    os.chmod(short, 0o600)
    with pytest.raises(vc.VaultClientError, match="64 byte values"):
        vc.load_keypair(str(short))
    with pytest.raises(vc.VaultClientError, match="not found"):
        vc.load_keypair(str(tmp_path / "absent.json"))


