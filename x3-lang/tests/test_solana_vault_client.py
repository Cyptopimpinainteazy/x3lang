def test_confirmed_send_submits_exactly_the_rust_transaction(tmp_path):
    h = Harness(tmp_path)
    assert h.run(*EXECUTE, "--keypair", h.agent_key, "--send") == vc.EXIT_OK
    assert len(h.cluster.sent) == 1
    expected = V["transactions"]["execute"]
    wire = h.cluster.sent[0]["wire"]
    assert wire == b"\x01" + bytes.fromhex(expected["signature_hex"]) + bytes.fromhex(expected["message_hex"])
    assert h.cluster.sent[0]["options"]["skipPreflight"] is False
    announced, final = json.loads(h.lines[1]), json.loads(h.lines[-1])
    assert announced["signature"] == vc.ed25519.b58encode(bytes.fromhex(expected["signature_hex"]))
    assert announced["message_sha256"] == hashlib.sha256(bytes.fromhex(expected["message_hex"])).hexdigest()
    assert announced["explorer"].endswith("?cluster=devnet")
    assert final == {"as_expected": True, "error": None, "finalized": True, "sent": True,
                     "signature": announced["signature"], "slot": 424242}
    # The signature is announced before the transaction is submitted.
    assert h.cluster.methods().index("sendTransaction") > h.cluster.methods().index("getLatestBlockhash")
    for secret in (OWNER_SEED, AGENT_SEED):
        assert secret.hex() not in h.output() and str(list(secret)) not in h.output()


