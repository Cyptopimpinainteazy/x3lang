def token_account(mint, owner, amount, *, delegate=None, state=1, close_authority=None):
    def option(key):
        return (b"\x01\x00\x00\x00" + key) if key else bytes(36)
    raw = mint + owner + amount.to_bytes(8, "little") + option(delegate) + bytes([state]) + bytes(12) \
        + bytes(8) + option(close_authority)
    assert len(raw) == vc.TOKEN_ACCOUNT_SIZE
    return raw


def mint_account(decimals=6):
    raw = bytes(36) + (10 ** 12).to_bytes(8, "little") + bytes([decimals, 1]) + bytes(36)
    assert len(raw) == vc.MINT_SIZE
    return raw


class FakeCluster:
    """Answers the JSON-RPC methods the client uses and records every call."""

    def __init__(self, genesis=DEVNET):
        self.genesis = genesis
        self.accounts = {}
        self.calls = []
        self.sent = []
        self.simulation = {"err": None, "logs": ["Program log: ok"], "unitsConsumed": 31_000}
        self.final_status = {"confirmationStatus": "finalized", "err": None, "slot": 424242}
        self.statuses_before_final = 1
        self.put(PROGRAM, bytes(36), owner=bytes([2] * 32), executable=True)
        self.put(MINT, mint_account(), owner=vc.TOKEN_PROGRAM)
        self.put(VAULT_TOKEN, token_account(MINT, POLICY, 40_000_000), owner=vc.TOKEN_PROGRAM)
        self.put(DEST_TOKEN, token_account(MINT, DEST_OWNER, 0), owner=vc.TOKEN_PROGRAM)
        self.put(OWNER_TOKEN, token_account(MINT, OWNER, 5), owner=vc.TOKEN_PROGRAM)
        self.put(POLICY, POLICY_STATE, owner=PROGRAM)

    def put(self, address, data, *, owner, executable=False):
        self.accounts[vc.pubkey_text(address)] = {
            "data": [base64.b64encode(data).decode(), "base64"], "owner": vc.pubkey_text(owner),
            "lamports": 2_000_000, "executable": executable}

    def methods(self):
        return [call["method"] for call in self.calls]

    def __call__(self, method, url, headers, body, timeout):
        call = json.loads(body)
        self.calls.append(call)
        name, params = call["method"], call["params"]
        if name == "getGenesisHash":
            result = self.genesis
        elif name == "getAccountInfo":
            result = {"value": self.accounts.get(params[0])}
        elif name == "simulateTransaction":
            assert params[1]["sigVerify"] is False and params[1]["replaceRecentBlockhash"] is True
            result = {"value": self.simulation}
        elif name == "getLatestBlockhash":
            result = {"value": {"blockhash": V["recent_blockhash"], "lastValidBlockHeight": 1}}
        elif name == "sendTransaction":
            wire = base64.b64decode(params[0])
            self.sent.append({"wire": wire, "options": params[1]})
            result = vc.ed25519.b58encode(wire[1:65])
        elif name == "getSignatureStatuses":
            if self.statuses_before_final > 0:
                self.statuses_before_final -= 1
                result = {"value": [None]}
            else:
                result = {"value": [self.final_status]}
        else:
            raise AssertionError(f"unexpected RPC method {name}")
        return 200, json.dumps({"jsonrpc": "2.0", "id": call["id"], "result": result}).encode()


class Harness:
    def __init__(self, tmp_path, cluster=None, answer="yes"):
        self.cluster = cluster or FakeCluster()
        self.owner_key = write_keypair(tmp_path, "owner.json", OWNER_SEED)
        self.agent_key = write_keypair(tmp_path, "agent.json", AGENT_SEED)
        self.answer = answer
        self.prompts = []
        self.lines = []
        self.ticks = 0.0

    def run(self, *argv, cluster_name="devnet"):
        args = vc.build_parser().parse_args(list(argv[:1]) + [
            "--rpc-url", "https://rpc.example.invalid", "--cluster", cluster_name, "--program", V["program"],
        ] + list(argv[1:]))

        def confirm(prompt):
            self.prompts.append(prompt)
            return self.answer == "yes"

        def clock():
            self.ticks += 1.0
            return self.ticks

        return vc.dispatch(args, out=self.lines.append, transport=self.cluster, confirm=confirm,
                           sleep=lambda _seconds: None, clock=clock, wall_clock=lambda: NOW)

    def json(self, index=0):
        return json.loads(self.lines[index])

    def output(self):
        return "\n".join(self.lines)


EXECUTE = ("execute", "--policy", V["policy"])


def test_dry_run_simulates_and_never_signs_or_sends(tmp_path):
    h = Harness(tmp_path)
