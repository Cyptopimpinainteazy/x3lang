@pytest.mark.parametrize("name", ["initialize", "approve", "execute", "cancel", "revoke", "withdraw"])
def test_instruction_message_and_signature_match_rust(name):
    seed, payer, instruction = vector_instructions()[name]
    expected = V["transactions"][name]
    assert instruction.data.hex() == expected["data_hex"]
    message = vc.compile_message(payer, instruction, BLOCKHASH)
    assert message.hex() == expected["message_hex"]
    signature = vc.Keypair(payer, seed).sign(message)
    assert signature.hex() == expected["signature_hex"]
    wire = vc.wire_transaction(signature, message)
    assert wire == b"\x01" + signature + message


